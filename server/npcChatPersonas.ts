// Returns the persona system prompt(s) for an NPC (Sonya gets an extra restrained
// line when the player blamed her).
export function personaPrompt(npcId: NpcId, sonyaBlamed: boolean): string {
  switch (npcId) {
    case 'sonya-sokolova':
      return sonyaBlamed ? `${SONYA}\n${SONYA_BLAMED}` : SONYA
    case 'kirill-morozov':
      return KIRILL
    case 'alina-belova':
      return ALINA
    case 'ilya-vlasov':
      return ILYA
  }
}

export function safetyRules(): string {
  return COMMON_RULES
}
